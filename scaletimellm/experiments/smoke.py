"""Fast end-to-end smoke pipeline used by CI and the Makefile."""

from __future__ import annotations

import json
import os
import time
from pathlib import Path
from typing import Any

from scaletimellm.analysis.aggregate import run_aggregation
from scaletimellm.analysis.compute_optimal import run_compute_optimal
from scaletimellm.analysis.tables import aggregate_by_task_strategy_budget
from scaletimellm.config import ExperimentConfig, ModelConfig, load_config
from scaletimellm.experiments.sweep import run_sweep


def smoke_config(base_path: str | Path = "configs/smoke.yaml") -> ExperimentConfig:
    """Build a tiny but complete mock-backend sweep configuration."""
    config = load_config(base_path)
    config.name = "smoke"
    config.models = [
        ModelConfig(
            name="mock-small",
            n_params=32_000_000,
            mock_accuracy=0.48,
            mock_verbosity=0.5,
        ),
        ModelConfig(
            name="mock-large",
            n_params=96_000_000,
            mock_accuracy=0.56,
            mock_verbosity=0.5,
        ),
    ]
    config.model = config.models[0]
    config.tasks = ["synthetic"]
    config.task = "synthetic"
    config.strategies = ["greedy", "self_consistency"]
    config.strategy = "self_consistency"
    config.budgets = [1, 2, 4]
    config.seeds = [0]
    config.n_problems = 6
    config.offline = True
    config.smoke = True
    return config


def run_smoke(
    output_dir: str | Path = "results/smoke",
    base_config: str | Path = "configs/smoke.yaml",
    n_boot: int = 200,
) -> dict[str, Any]:
    """Run a complete tiny sweep, aggregate it, and write summary.json."""
    started = time.perf_counter()
    os.environ["SCALETIMELLM_OFFLINE"] = "1"
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    # Keep smoke raw files in an isolated work directory so ``SMOKE_OUT=results``
    # can write the CI-visible summary without contaminating the full sweep.
    work = output / "smoke_work"
    config = smoke_config(base_config)
    sweep = run_sweep(config, output_dir=work, resume=False)
    frame, cells, difficulty = run_aggregation(
        raw_dir=work / "raw" / "sweep", output_dir=work, n_boot=n_boot
    )
    compute = run_compute_optimal(
        frame,
        cells,
        difficulty,
        output_path=work / "compute_optimal.json",
        n_boot=n_boot,
    )
    grid = aggregate_by_task_strategy_budget(cells)
    summary = {
        "smoke": True,
        "backend": sweep["backend"],
        "synthetic": True,
        "models": sweep["models"],
        "tasks": sweep["tasks"],
        "strategies": sweep["strategies"],
        "budgets": sweep["budgets"],
        "seeds": sweep["seeds"],
        "n_problems": sweep["n_problems"],
        "cells": sweep["cells"],
        "records": sweep["records"],
        "wall_time_s": time.perf_counter() - started,
        "headline": grid.to_dict(orient="records"),
        "best_per_task": compute["best_strategy_per_task"],
        "raw_dir": str(work / "raw" / "sweep"),
        "aggregate_csv": str(output / "aggregate.csv"),
    }
    (work / "aggregate.csv").replace(output / "aggregate.csv")
    (output / "summary.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True), encoding="utf-8"
    )
    lines = [
        "# ScaleTimeLLM smoke report",
        "",
        "Tiny end-to-end mock-backend run generated by `python -m scaletimellm.cli smoke`.",
        "",
        f"- models: {', '.join(summary['models'])}",
        f"- cells: {summary['cells']}; records: {summary['records']}",
        f"- wall time: {summary['wall_time_s']:.2f}s",
        f"- best strategy: {summary['best_per_task']}",
        "",
        "This is a pipeline check, not a scientific result.",
        "",
    ]
    (output / "REPORT.md").write_text("\n".join(lines), encoding="utf-8")
    return summary
